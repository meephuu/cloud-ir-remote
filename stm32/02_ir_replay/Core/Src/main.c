static void uart_print(const char *s)
{
  HAL_UART_Transmit(&huart2, (uint8_t *)s, strlen(s), HAL_MAX_DELAY);
}

static void carrier(uint8_t on)
{
  __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, on ? CARRIER_ON : 0);
}

// Start sending saved_buf: [0]=mark, [1]=space, [2]=mark ...
static void ir_send_saved(void)
{
  if (saved_count == 0 || tx_busy) return;
  tx_busy  = 1;
  tx_index = 0;
  carrier(1);                                         // first segment is a mark
  __HAL_TIM_SET_AUTORELOAD(&htim5, saved_buf[0] - 1);
  __HAL_TIM_SET_COUNTER(&htim5, 0);
  __HAL_TIM_CLEAR_FLAG(&htim5, TIM_FLAG_UPDATE);      // avoid an instant false "segment done"
  HAL_TIM_Base_Start_IT(&htim5);
}

// TIM5: current mark/space is over -> move to the next one
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM5)
  {
    tx_index++;
    if (tx_index >= saved_count) {                    // all done
      carrier(0);
      HAL_TIM_Base_Stop_IT(&htim5);
      tx_busy = 0;
    } else {
      carrier((tx_index % 2) == 0);                   // even index = mark, odd = space
      __HAL_TIM_SET_AUTORELOAD(&htim5, saved_buf[tx_index] - 1);
    }
  }
}

// TIM2: an edge from the IR receiver (same as step 1, plus loopback flag)
void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM2 && htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1)
  {
    uint32_t now = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1);
    if (!ir_started) {
      ir_started = 1;
      ir_from_tx = tx_busy;                           // did this start during our own transmission?
    } else if (ir_count < IR_MAX_EDGES) {
      ir_buf[ir_count++] = now - ir_last_edge;
    } else {
      ir_overflow = 1;
    }
    ir_last_edge = now;
  }
}

// B1 blue button -> request a replay (with simple debounce)
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  if (GPIO_Pin == B1_Pin) {
    uint32_t now = HAL_GetTick();
    if (now - last_press > 300) {
      last_press = now;
      tx_request = 1;
    }
  }
}
