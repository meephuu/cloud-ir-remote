/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART2_UART_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_TIM5_Init();
  /* USER CODE BEGIN 2 */
  uart_print("\r\n=== IR replay test ===\r\n");
    uart_print("1) Tap a remote button at the KY-022 to save it\r\n");
    uart_print("2) Press the blue B1 button to replay it\r\n");
    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);   // carrier timer runs; CCR=0 keeps LED off
    HAL_TIM_IC_Start_IT(&htim2, TIM_CHANNEL_1);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
	  // --- B1 pressed: send the saved code ---
	      if (tx_request)
	      {
	        tx_request = 0;
	        if (saved_count == 0) {
	          uart_print("Nothing saved yet - tap a remote at the receiver first.\r\n");
	        } else {
	          sprintf(msg, "Sending %u durations...\r\n", saved_count);
	          uart_print(msg);
	          ir_send_saved();
	        }
	      }

	      // --- a received signal has finished ---
	      if (ir_started)
	      {
	        __disable_irq();
	        uint32_t last = ir_last_edge;
	        uint32_t now  = __HAL_TIM_GET_COUNTER(&htim2);
	        __enable_irq();

	        if (now - last > IR_END_GAP_US)
	        {
	          HAL_TIM_IC_Stop_IT(&htim2, TIM_CHANNEL_1);

	          uint32_t total = 0;
	          for (uint16_t i = 0; i < ir_count; i++) total += ir_buf[i];

	          if (ir_from_tx) {
	            // We heard our own transmission
	            sprintf(msg, "Loopback: received %u of %u durations, %lu us -> %s\r\n",
	                    ir_count, saved_count, total,
	                    (ir_count == saved_count) ? "MATCH" : "DIFFERENT");
	          } else if (!tx_busy) {
	            // A real remote: save it for replay
	            for (uint16_t i = 0; i < ir_count; i++) saved_buf[i] = ir_buf[i];
	            saved_count = ir_count;
	            sprintf(msg, "Saved: %u durations, %lu us%s. Press B1 to replay.\r\n",
	                    ir_count, total, ir_overflow ? " (BUFFER FULL!)" : "");
	          }
	          uart_print(msg);
	          HAL_GPIO_TogglePin(LD2_GPIO_Port, LD2_Pin);

	          ir_count = 0; ir_started = 0; ir_overflow = 0; ir_from_tx = 0;
	          HAL_TIM_IC_Start_IT(&htim2, TIM_CHANNEL_1);
	        }
	      }
	    }   // <-- closes while (1). Keep this brace!
  /* USER CODE END 3 */
}

